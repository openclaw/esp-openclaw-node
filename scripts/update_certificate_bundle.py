#!/usr/bin/env python3
"""Derive the example firmware's public CA data from its selected ESP-IDF SDK."""

import argparse
import hashlib
from pathlib import Path
import re
import ssl


REMOVED_ROOTS = {
    # Debian DSA-6572-1: remove these anchors to reject the eMudhra incident chains.
    "d7a7a0fb5d7e2731d771e9484ebcdef71d5f0c3e0a2948782bc83ee0ea699ef4",
    "86a1ecba089c4a8d3bbe2734c612ba341d813e043cf9e8a862cd5c57a36bbe6b",
}
CERTIFICATE = re.compile(rb"-----BEGIN CERTIFICATE-----\r?\n.*?-----END CERTIFICATE-----\r?\n?", re.S)


def filtered_bundle(idf_path):
    bundle_dir = idf_path / "components/mbedtls/esp_crt_bundle"
    result = bytearray(
        b"## OpenClaw example public CA bundle.\n"
        b"## Generated by scripts/update_certificate_bundle.py; see certificates/README.md.\n"
        b"## Mozilla/curl provenance and notices from the selected SDK follow.\n\n"
    )
    for name in ("cacrt_all.pem", "cacrt_local.pem"):
        source = (bundle_dir / name).read_bytes()
        # Keep the upstream preamble and every retained PEM block verbatim. Certificate
        # headings are omitted so removed roots cannot leave misleading labels behind.
        preamble = source.split(b"\n\n", 1)[0]
        result.extend(preamble + b"\n\n")
        for match in CERTIFICATE.finditer(source):
            pem = match.group()
            der = ssl.PEM_cert_to_DER_cert(pem.decode("ascii"))
            if hashlib.sha256(der).hexdigest() not in REMOVED_ROOTS:
                result.extend(pem.rstrip() + b"\n\n")
    return bytes(result).rstrip() + b"\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--idf-path", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    arguments.output.write_bytes(filtered_bundle(arguments.idf_path))


if __name__ == "__main__":
    main()
